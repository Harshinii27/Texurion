"""Texurion brand assets: the original pixel-built "T" identity.

All logo art lives in ``assets/branding`` and is generated by
``generate_brand_assets.py``. This module is the single source of truth for
the application, so the sidebar lockup, favicon and reports never drift apart.
"""

import os

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS_DIR = os.path.join(_ROOT, "assets", "branding")

# SVG (vector) sources.
ICON_SVG_PATH = os.path.join(ASSETS_DIR, "texurion_icon.svg")
FAVICON_SVG_PATH = os.path.join(ASSETS_DIR, "texurion_favicon.svg")
LOGO_SVG_PATH = os.path.join(ASSETS_DIR, "texurion_logo.svg")
LOGO_DARK_SVG_PATH = os.path.join(ASSETS_DIR, "texurion_logo_dark.svg")

# Raster (transparent PNG) exports for contexts that need them.
ICON_PNG_PATH = os.path.join(ASSETS_DIR, "texurion_icon.png")
FAVICON_PNG_PATH = os.path.join(ASSETS_DIR, "texurion_favicon.png")
LOGO_PNG_PATH = os.path.join(ASSETS_DIR, "texurion_logo.png")
LOGO_DARK_PNG_PATH = os.path.join(ASSETS_DIR, "texurion_logo_dark.png")


def _read_text(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except OSError:
        return ""


ICON_SVG = _read_text(ICON_SVG_PATH)
FAVICON_SVG = _read_text(FAVICON_SVG_PATH)


def icon_svg() -> str:
    """Inline SVG markup of the pixel-T symbol (transparent background)."""

    return ICON_SVG


def favicon_svg() -> str:
    return FAVICON_SVG


def icon_path():
    """Path to the transparent icon PNG, or None if it is unavailable."""

    return ICON_PNG_PATH if os.path.isfile(ICON_PNG_PATH) else None


def favicon_path():
    """Path to favicon art suitable for ``st.set_page_config(page_icon=...)``."""

    for path in (FAVICON_PNG_PATH, ICON_PNG_PATH):
        if os.path.isfile(path):
            return path
    return None


def logo_path(dark=False):
    for path in ((LOGO_DARK_PNG_PATH if dark else LOGO_PNG_PATH),
                 ICON_PNG_PATH):
        if os.path.isfile(path):
            return path
    return None
